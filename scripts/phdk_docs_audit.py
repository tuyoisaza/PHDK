#!/usr/bin/env python3
"""Read-only-by-default PHDK project document audit and bounded index writer.

This inspects text metadata and paths; it never infers approval or implementation.
It does not run applications, UAT, Git operations or a background process.
"""
from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from collections import defaultdict
from pathlib import Path

CATEGORIES = ("intents", "briefs", "decisions", "plans")
FILE_RE = re.compile(r"^(?P<slug>[a-z0-9]+(?:-[a-z0-9]+)*)\.v(?P<version>0|[1-9][0-9]*)\.md$")
DOC_ID_RE = re.compile(r"^(?:[a-z0-9]+(?:-[a-z0-9]+)*|ADR-[0-9]{4,})$")
STATUSES = {"draft", "active", "superseded", "archived"}
AUTHORITIES = {"owner-approved", "owner-request", "agent-selected", "inherited", "unknown"}
STAMP = "# Generated by phdk_docs_audit.py — DO NOT EDIT; source of truth: document front matter."
LEGACY_ROOT = {
    "PROJECT_INTENT.md", "PROJECT_BRIEF.md", "PRD.md", "FEATURES.md",
    "REQUIREMENTS_TRACEABILITY.md", "SOLUTION_ARCHITECTURE.md",
    "REPOSITORY_ARCHITECTURE.md", "UX_ARCHITECTURE.md", "MILESTONE_PLAN.md",
    "IMPLEMENTATION_PLAN.md", "ARCHITECTURE_DECISIONS.md",
    "UI_DESIGN_SYSTEM.md", "UX_UI_DECISIONS.md",
}


def metadata(path: Path) -> tuple[dict[str, str] | None, str | None]:
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        return None, str(exc)
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None, "missing first-line YAML-style front matter"
    fields: dict[str, str] = {}
    for line in lines[1:]:
        if line.strip() == "---":
            return fields, None
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if ":" not in line:
            return None, "invalid front matter line"
        key, value = line.split(":", 1)
        key, value = key.strip(), value.strip().strip('"').strip("'")
        if not re.fullmatch(r"[a-z][a-z_]*", key) or not value:
            return None, "invalid or empty front matter value"
        if key in fields:
            return None, f"duplicate front matter field: {key}"
        fields[key] = value
    return None, "unterminated front matter"


def valid_day(value: str) -> bool:
    try:
        return dt.date.fromisoformat(value).isoformat() == value
    except ValueError:
        return False


def audit(root: Path, changed: set[str]) -> tuple[list[str], list[str], list[dict[str, object]]]:
    errs: list[str] = []
    warns: list[str] = []
    records: list[dict[str, object]] = []
    docs = root / "docs"
    if docs.is_symlink():
        return ["docs/ must not be a symlink"], [], []
    for category in CATEGORIES:
        base = docs / category
        if base.is_symlink():
            errs.append(f"docs/{category}/ must not be a symlink")
            continue
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*.md")):
            if path.is_symlink():
                errs.append(f"{path.relative_to(root)}: symlinks are unsupported")
                continue
            rel = path.relative_to(root).as_posix()
            if path.name == "README.md":
                continue
            match = FILE_RE.fullmatch(path.name)
            if not match:
                if rel in changed:
                    errs.append(f"{rel}: changed durable document needs kebab-case.vN.md")
                else:
                    warns.append(f"LEGACY_COMPATIBLE: {rel} (migrate on material revision)")
                continue
            fields, problem = metadata(path)
            if problem:
                errs.append(f"{rel}: {problem}")
                continue
            assert fields is not None
            required = ("doc_id", "version", "status", "created_at", "updated_at", "authority")
            for name in required:
                if not fields.get(name):
                    errs.append(f"{rel}: missing {name}")
            if any(name not in fields for name in required):
                continue
            doc_id = fields["doc_id"]
            v = int(match.group("version"))
            if not DOC_ID_RE.fullmatch(doc_id):
                errs.append(f"{rel}: invalid doc_id {doc_id!r}")
            if fields["version"] != f"v{v}":
                errs.append(f"{rel}: filename/front matter version mismatch")
            if fields["status"] not in STATUSES:
                errs.append(f"{rel}: invalid status")
            if fields["authority"] not in AUTHORITIES:
                errs.append(f"{rel}: invalid authority")
            if not valid_day(fields["created_at"]) or not valid_day(fields["updated_at"]):
                errs.append(f"{rel}: invalid ISO dates")
            elif fields["updated_at"] < fields["created_at"]:
                errs.append(f"{rel}: updated_at precedes created_at")
            if category == "decisions" and match.group("slug").startswith("adr-"):
                prefix = re.match(r"^adr-([0-9]{4,})-", match.group("slug"))
                if not prefix or doc_id != f"ADR-{prefix.group(1)}":
                    errs.append(f"{rel}: ADR filename/doc_id mismatch")
            records.append({"category": category, "id": doc_id, "version": v,
                            "status": fields["status"], "path": rel})
    keys: dict[tuple[str, str], list[dict[str, object]]] = defaultdict(list)
    for rec in records:
        keys[(str(rec["category"]), str(rec["id"]))].append(rec)
    for key, versions in keys.items():
        active = [r for r in versions if r["status"] == "active"]
        if len(active) > 1:
            errs.append(f"{key}: multiple active document baselines")
        if len({r["version"] for r in versions}) != len(versions):
            errs.append(f"{key}: duplicate version identifiers")
    for rel in changed:
        relpath = Path(rel)
        if relpath.is_absolute() or ".." in relpath.parts:
            errs.append(f"unsafe --changed path: {rel}")
            continue
        parts = relpath.parts
        if len(parts) >= 3 and parts[0] == "docs" and parts[1] == "images":
            # A non-versioned legacy image asset is only a failure when changed.
            if not any(re.fullmatch(r"v(?:0|[1-9][0-9]*)", p) for p in parts[3:-1]):
                errs.append(f"{rel}: new/changed design asset needs docs/images/<topic>/vN/<asset>")
    return errs, warns, records


def make_index(records: list[dict[str, object]]) -> str:
    groups: dict[tuple[str, str], list[dict[str, object]]] = defaultdict(list)
    for rec in records:
        groups[(str(rec["category"]), str(rec["id"]))].append(rec)
    result = [
        STAMP,
        "",
        "# Project documentation index",
        "",
        "This is a locator, not owner approval, a task queue, acceptance proof, or deployment status.",
        "",
        "| Category | Document ID | Active baseline | Working draft | All versions |",
        "|---|---|---|---|---|",
    ]
    for (category, doc_id), versions in sorted(groups.items()):
        versions.sort(key=lambda r: int(r["version"]))
        active = next((r for r in versions if r["status"] == "active"), None)
        drafts = [r for r in versions if r["status"] == "draft"]
        draft = drafts[-1] if drafts else None
        def link(rec: dict[str, object] | None) -> str:
            if rec is None:
                return "—"
            path = str(rec["path"])
            return f"[v{rec['version']}]({path[5:]})"
        all_links = ", ".join(link(r) for r in versions)
        result.append(f"| {category} | \`{doc_id}\` | {link(active)} | {link(draft)} | {all_links} |")
    result.extend(["", "Legacy root documents remain valid when unmodified; read the canonical PHDK documentation standard for migration rules.", ""])
    return "\n".join(result)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="read-only consistency audit (default)")
    mode.add_argument("--sync-index", action="store_true",
                      help="write only a PHDK-generated docs/INDEX.md within authorized work")
    parser.add_argument("--changed", nargs="*", default=[], metavar="PATH",
                        help="changed paths relative to project root; enforce naming for these")
    args = parser.parse_args()
    root = args.root.resolve()
    if not root.is_dir():
        print(f"FAIL: missing project root {root}", file=sys.stderr)
        return 2
    errors, warnings, records = audit(root, set(args.changed))
    for issue in warnings:
        print("WARN: " + issue)
    index = root / "docs" / "INDEX.md"
    expected = make_index(records) if records else None
    if expected is not None:
        if index.is_symlink():
            errors.append("docs/INDEX.md must not be a symlink")
        elif index.exists():
            try:
                actual = index.read_text(encoding="utf-8")
                if not actual.startswith(STAMP):
                    errors.append("docs/INDEX.md is owner-maintained: do not overwrite; reconcile explicitly")
                elif actual != expected and not args.sync_index:
                    errors.append("docs/INDEX.md is stale (use --sync-index in authorized work)")
            except (OSError, UnicodeDecodeError) as exc:
                errors.append(f"docs/INDEX.md unreadable: {exc}")
        elif not args.sync_index:
            errors.append("docs/INDEX.md missing for versioned documents")
    if args.sync_index and not errors and expected is not None:
        index.parent.mkdir(parents=True, exist_ok=True)
        index.write_text(expected, encoding="utf-8")
        print("UPDATED: docs/INDEX.md")
    for issue in errors:
        print("FAIL: " + issue, file=sys.stderr)
    if errors:
        return 1
    print(f"PASS: {len(records)} versioned documents; "
          f"{len(warnings)} compatible legacy notes; "
          f"index {'current' if expected else 'not yet applicable'} (static only)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
